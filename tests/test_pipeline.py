import json
from pathlib import Path
import numpy as np
import pytest
import yaml
from optosky_raman.pipeline import run_pipeline
from optosky_raman.report import generate_report


def write_csv(path,shift=0):
    x=np.linspace(200,800,201); y=20+.01*x+80*np.exp(-4*np.log(2)*((x-495-shift)/40)**2)
    rows=['Data Generated by,Optosky Raman Microscope','扫描时间,2026-10-12 13:43:31',
          '积分时间(ms),10000','激光功率(mW),30','Raman Shift,Raw,Dark,Dark Subtracted,BaseLine Subtracted']
    rows.extend(f'{a},{b+100},100,{b},{b-20}' for a,b in zip(x,y))
    path.write_text('\n'.join(rows),encoding='utf-8')


def configuration(path):
    path.write_text(yaml.safe_dump({'preprocessing':{'sensitivity':{'enabled':False}},
        'fitting':{'max_components':1,'multistart':2,'shapes':['gaussian']},
        'plotting':{'formats':['png'],'dpi':75}}),encoding='utf-8')


def test_audit_analyze_compare_report_and_source_integrity(tmp_path):
    a=tmp_path/'a'; b=tmp_path/'b'; a.mkdir(); b.mkdir()
    write_csv(a/'-1.123cv.csv'); write_csv(b/'-1.123cv.csv',1)
    original=(a/'-1.123cv.csv').read_bytes()
    cfg=tmp_path/'settings.yaml'; configuration(cfg)
    audit=run_pipeline([a],tmp_path/'audit',cfg,'audit')
    assert audit['counts']['imported']==1
    assert audit['counts']['processed']==0
    analysis=run_pipeline([a],tmp_path/'analyze',cfg,'analyze')
    assert analysis['counts']['processed']==1
    assert (tmp_path/'analyze'/'results.json').exists()
    result_mtime=(tmp_path/'analyze'/'results.json').stat().st_mtime_ns
    generate_report(tmp_path/'analyze')
    assert result_mtime==(tmp_path/'analyze'/'results.json').stat().st_mtime_ns
    assert (tmp_path/'analyze'/'report.html').exists()
    compared=run_pipeline([a,b],tmp_path/'compare',cfg,'compare')
    assert compared['counts']['imported']==2
    assert compared['comparisons']['batch_pairs']==1
    assert (a/'-1.123cv.csv').read_bytes()==original


def test_bad_file_is_not_silently_ignored(tmp_path):
    data=tmp_path/'inputs'; data.mkdir(); write_csv(data/'-1.1cv.csv')
    (data/'broken.csv').write_text('not a spectrum',encoding='utf-8')
    result=run_pipeline([data],tmp_path/'out',None,'audit')
    assert result['counts']['failed']==1
    assert result['status']=='partial_failure'
    assert (tmp_path/'out'/'errors.json').exists()


def test_output_cannot_overwrite_input_directory(tmp_path):
    write_csv(tmp_path/'-1.1cv.csv')
    with pytest.raises(ValueError,match='output'):
        run_pipeline([tmp_path],tmp_path,None,'audit')


def test_empty_audit_does_not_report_observed_spectral_changes(tmp_path):
    inputs=tmp_path/'empty'; inputs.mkdir()
    result=run_pipeline([inputs],tmp_path/'out',None,'audit')
    assert result['counts']['imported']==0
    text=(tmp_path/'out/report.md').read_text(encoding='utf-8')
    assert '观察到光谱强度或谱形的变化' not in text


def test_report_works_across_windows_volumes(tmp_path,monkeypatch):
    inputs=tmp_path/'empty'; inputs.mkdir()
    run_pipeline([inputs],tmp_path/'saved',None,'audit')
    def cross_volume(*args,**kwargs):
        raise ValueError('path is on mount C:, start on mount E:')
    monkeypatch.setattr('os.path.relpath',cross_volume)
    generated=generate_report(tmp_path/'saved',tmp_path/'newreport')
    text=(tmp_path/'newreport/report.html').read_text(encoding='utf-8')
    assert 'file:///' in text
    assert 'html' in generated


def test_source_snapshot_preserves_line_endings(tmp_path):
    inputs=tmp_path/'inputs'; inputs.mkdir(); source=inputs/'-1.1cv.csv'; write_csv(source)
    raw_text=source.read_bytes().decode('utf-8-sig')
    result=run_pipeline([inputs],tmp_path/'out',None,'audit')
    snapshot=tmp_path/'out'/result['records'][0]['snapshot']
    assert snapshot.read_bytes().decode('utf-8')==raw_text
